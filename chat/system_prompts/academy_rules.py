# Each bot's FAQ; "what to bring" is read from it after a confirmed trial.
ACADEMY_FAQ_FILES = {
    "dopsy_fs_school": "academy_football_faq.md",
    "dopsy_boxing": "academy_boxing_faq.md",
}
_WHAT_TO_BRING_HEADING = "## Что взять с собой"
_KAZAKH_PREFIX = "Қазақша:"


def academy_what_to_bring(bot_name: str, lang: str) -> str:
    """The FAQ's «Что взять с собой» section in `lang` — the Russian text, or
    the part after «Қазақша:» — or "" when the FAQ has none. Read on every
    call, so an edit of the FAQ applies at once."""
    import config  # here, not at the top: config imports the prompts that import this module

    name = ACADEMY_FAQ_FILES.get(bot_name)
    if not name:
        return ""
    try:
        text = (Path(config.DOCUMENTS_PATH) / name).read_text(encoding="utf-8")
    except OSError:
        return ""
    start = text.find(_WHAT_TO_BRING_HEADING)
    if start < 0:
        return ""
    # The text after the heading line, up to the next section.
    body = text[start:].partition("\n")[2].split("\n## ")[0]
    ru, _, kk = body.partition(_KAZAKH_PREFIX)
    section = (kk if lang == "kk" and kk.strip() else ru).strip()
    if not section:
        return ""
    section = section[0].upper() + section[1:]
    # Text that doesn't open with its own lead-in («...понадобятся:») gets one.
    if not section.split("\n", 1)[0].endswith(":"):
        section = f"{'Не алып келу керек:' if lang == 'kk' else 'Что взять с собой:'}\n{section}"
    return section


